// Copies the map stamps' icons from game-icons.net (the @iconify-json/game-icons dev dependency)
// into src/lib/map/icons.generated.ts, so the app bundles only these, not all 4,000.
// Run after changing the list: node scripts/map-icons.mjs
// The icons are CC BY 3.0 (game-icons.net, by Lorc, Delapouite and contributors): keep the credit
// in Settings → Credits.

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const set = JSON.parse(readFileSync(require.resolve("@iconify-json/game-icons/icons.json"), "utf8"));

/** Stamp groups and the icons in them, in picker order. Architecture is drawn by us (stamps.ts). */
const GROUPS = {
  treasure: ["chest", "open-chest", "locked-chest", "two-coins", "coins-pile", "gems", "gem-pendant", "crown", "ring", "key", "scroll-unfurled", "round-potion", "health-potion"],
  creatures: ["dragon-head", "goblin-head", "orc-head", "troll", "minotaur", "imp", "cultist", "hooded-figure", "ghost", "shambling-zombie", "death-skull", "skull-crossed-bones", "spider-face", "snake", "rat", "bat", "wolf-head", "slime", "kraken-tentacle"],
  traps: ["wolf-trap", "mantrap", "box-trap", "spikes", "falling-rocks", "arrow-cluster", "poison-bottle", "fire", "trap-mask"],
  objects: ["door", "barrel", "wooden-crate", "table", "bed", "stone-throne", "bookshelf", "cauldron", "anvil", "torch", "campfire", "fire-bowl", "star-altar", "sword-altar", "tombstone", "coffin", "skull-in-jar", "cage", "cobweb", "mushrooms", "well", "ladder", "crossed-swords", "shield", "flag-objective", "position-marker"],
};

const lines = [];
for (const [group, names] of Object.entries(GROUPS)) {
  for (const name of names) {
    const icon = set.icons[name];
    if (!icon) throw new Error(`No icon "${name}" in game-icons`);
    const paths = [...icon.body.matchAll(/<path fill="currentColor" d="([^"]+)"\/>/g)].map((m) => m[1]);
    if (!paths.length) throw new Error(`"${name}" isn't plain filled paths`);
    const label = name.replace(/-/g, " ").replace(/^./, (c) => c.toUpperCase());
    lines.push(`  { id: ${JSON.stringify(name)}, label: ${JSON.stringify(label)}, group: ${JSON.stringify(group)}, d: ${JSON.stringify(paths.join(" "))} },`);
  }
}

writeFileSync(
  new URL("../src/lib/map/icons.generated.ts", import.meta.url),
  `// Generated by scripts/map-icons.mjs from game-icons.net (CC BY 3.0, by Lorc, Delapouite and
// contributors; credited in Settings → Credits). Don't edit by hand: change the list there and run it.
// Paths are in a 512 × 512 box.

export type GameIcon = { id: string; label: string; group: "treasure" | "creatures" | "traps" | "objects"; d: string };

export const GAME_ICONS: GameIcon[] = [
${lines.join("\n")}
];
`,
);
console.log(`Wrote ${lines.length} icons.`);
